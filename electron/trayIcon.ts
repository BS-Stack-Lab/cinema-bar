import { nativeImage } from 'electron';
export function createTrayIcon() {
  const width = 22;
  const bitmap = Buffer.alloc(width * width * 4);
  const pattern = [
    '0000111100111100000000',
    '0001111111111110000000',
    '0011100111100111000000',
    '0011000011000011000000',
    '0011100111100111000000',
    '0001111111111110000000',
    '0000111100111100000000',
    '0000000000000000000000',
    '0011111111111111000000',
    '0011111111111111000100',
    '0011111111111111011100',
    '0011110011001111111100',
    '0011110011001111111100',
    '0011111111111111011100',
    '0011111111111111000100',
    '0011111111111111000000',
    '0000000000000000000000',
    '0000110000001100000000',
    '0000110000001100000000',
    '0000000000000000000000',
    '0000000000000000000000',
    '0000000000000000000000',
  ];
  pattern.forEach((row, y) =>
    [...row].forEach((pixel, x) => {
      if (pixel === '1') bitmap[(y * width + x) * 4 + 3] = 255;
    }),
  );
  const icon = nativeImage.createFromBitmap(bitmap, { width, height: width });
  icon.setTemplateImage(true);
  return icon;
}
